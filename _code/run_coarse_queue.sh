# 🔴 _F2 批次(2026-09-05)—— 证据强度加权后的对比:
#   E2 实测发现团队 tilt 仍被压平(+0.570 vs 单 Agent +0.865，而 tilt 与收益相关 +0.714)。
#   统计各角色发言用词倾向找到机制:
#     geomechanics_expert 净倾向 +0.42(最强反 tilt)，而它只有 156 字纯文献、
#     零本项目实测数据;economics_analyst -0.75(最强促 tilt)，有本油藏经济数据。
#     **零数据的类比角色与有实测的角色等权**，是主收益轴被压平的直接原因。
#   三处优化(均不删角色，只纠正"话语权与证据强度脱钩"):
#     ① 总工按证据强度裁决:literature 类顾虑不足以否决 simulation 类正向证据;
#        多角色同一顾虑若依据都是 literature，仍只算一份，不因人多而变强。
#     ② 文献类角色自限:明确无本油藏实测数据，"不要因为不确定就把上限压低 ——
#        那是把无知当成保守";无证据反对时须明说。
#     ③ 意见列表按证据强度排序，实测类先出现。
#   诊断验证:同口径 tilt +0.231 → +0.360(+56%)。
#
# 🔴 _E2 批次(2026-09-05)—— 对等性修复后的定稿对比:
#   ① 共享背景(tilt 先验 + 领域规则)此前只发给 7 个角色中的 4 个，
#      而没拿到的三个恰好是 PERSPECTIVE 限定"只能给上限/风险/否决"的角色 ——
#      既不给数据又限定只能唱反调，纯稀释;更关键的是单 Agent 臂用的
#      economics_analyst 恰好在"拿到"组。现提升为**全体共享背景**(7 角色完全一致)，
#      分歧只来自各自的专属数据。
#   ② 单 Agent 臂由 economics_analyst 改为 reservoir_engineer:
#      目标函数是 NPV，而七个角色里只有 economics_analyst 直接读到油价与成本，
#      其余六个只看物理量 —— 用它当单 Agent 等于挑了最强的那个。
#      改用 reservoir_engineer 是"靠近严格但不极端":核心领域角色、只读物理量、
#      非文献边缘角色。不选 constraint_auditor(293 字)或 geomechanics_expert(156 字)
#      是为了不走向刻意削弱。
#
# 🔴 _D2 批次(2026-09-05)—— Workflow 五维审计(45 条发现)后按**类**修复:
#   审计的 45 条归并为 5 类，每类配一条结构性防线(_tests/test_truth.py):
#     ① 同一个量有多套算法 → 抽 fc_truth.py 为唯一真源;
#        统一 6 个文件 8 处的 trapezoid(inj_actual)→field_cum(差最大 3.12pp，14 例结论相反);
#        提示词里的基准产油与水价改为从真源/命令行取，不再硬编码。
#     ② 标识符用位置而非内容 → 模拟缓存键并入 θ 指纹;
#        提示词引用历史方案改用全局 key(此前"候选#N"跨轮复用制造伪造证据)。
#     ③ 防线是黑名单而非白名单 → 泄露测试改为来源白名单;
#        实证黑名单漏掉了第三处泄露(tilt 表命中 0 条却由 228/234 个智能体解出的算例支撑)。
#     ④ 状态更新与控制流顺序错 → incumbent 更新移到 break 之前，并加测试断言顺序。
#     ⑤ 注释断言与代码不符 → 关键注释配对应测试(我曾只改注释未验证顺序)。
#   另修:_run_sim 抛 SystemExit 而 except Exception 接不住(模拟一失败整次运行崩掉)。
#   tilt 先验已用**仅随机采样的 275 个算例**重算(spearman +0.714，此前 +0.894 含智能体解)。
#
# 🔴 _C2 批次(2026-09-05)—— 子智能体元思维分析后的五处修复:
#   子智能体反证了我的"缺精英保留"诊断:方案 churn full7 1.089 vs one1 1.108，
#   p=0.947 无差异 —— 单 Agent 推翻上一轮的幅度一样大却不掉分，故该机制非病因。
#   真病因有二:
#     (A) 本问题的 ΔNPV 几乎是**一个标量**的函数:
#         tilt = 前两段均值 - 后两段均值，spearman +0.894、R² 0.700 (n=1061)。
#         而七角色按油藏工程学科分工，其中五个的关注轴上 NPV 梯度≈0，
#         于是系统性把 tilt 压平:full7 +0.551 vs one1 +1.054 (p=3.8e-05)。
#     (B) **总工从未直接读到过模拟器的任何数字**:hist 只进 readers(:737)、
#         sim_txt 只进审计员(:931)、ASK_CHIEF 不含二者。真值须经 7 个 LLM 转述，
#         这是转述信道，保真度随中继节点数下降 —— 角色越多损害越大。
#   五处修复:
#     ① 模拟器真值直连总工(新增"第零部分"，冲突时以其为准);
#     ② tilt 分箱统计显式化(方向与量级，不含任何具体方案);
#     ③ 修 incumbent 更新与 break 的 off-by-one;
#     ④ 冠军候选复用已有实测，不重复吃模拟预算;
#     ⑤ 清理三处过期/污染文本(已取消的派系分歧、失效的"55%被否决"、
#        被总工当真值引用并触发 fabricated_evidence 的硬编码示例)。
#
# 🔴 _B2 批次(2026-09-05)—— 在 _A2 基础上加入**精英保留(elitism)**:
#   实测 _A2 的 Team 七次里六次"越跑越差":首轮均值 +431.4M → 终态 +291.8M，
#   闭环净效果 **-139.6M(-32%)**;而单 Agent 只掉 12.9M。
#   诊断:七个角色每轮都提出新顾虑，总工每轮响应最新的那个，
#   于是不断推翻上一轮**已被模拟器验证过**的好方案。角色越多，被推翻得越频繁。
#   **这不是"角色有害"，是我的迭代机制漏了 elitism。**
#   修法:(a) 现任冠军(迄今模拟器验证的最优)写进总工提示词，
#         并要求"已被验证的成绩不应被未验证的顾虑推翻";
#        (b) 冠军 theta 直接作为一个候选参与评分，保证不会丢失;
#        (c) 终态口径改为"历史最优"而非"最后一轮"——迭代优化的标准做法。
#
# 🔴 _A2 批次(2026-09-05)—— 清除**两处**泄露后的干净对比:
#   第二处泄露(用户怀疑单 Agent 作弊后查实):economics_analyst 一直在读
#   sweep.json，其每行为「水价 X → 最佳方案=<算例名>，ΔNPV=+514.3M，注水量 -2.35%」
#   —— 是答案卡片而非市场事实;而单 Agent 臂保留的恰好是该角色，
#   造成"单 Agent +490M 远高于 Agent Team +197M"的反常排序。
#   现改为只给市场与成本事实 + 由油价/成本算出的经济极限含水率。
#
#   设计原则(用户 2026-09-05 拍板):**大概公平即可，不追求绝对对等**。
#   领域数据本就该归专家所有 —— 那是"专家"的定义;不给的只有**答案**。
#   无 Agent 臂 = B2 一维均匀缩放(+62.6M，7 次模拟，1 个决策变量，零智能零知识)。
#
# 🔴 _Z 批次(2026-09-04)—— 清除数据泄露后的第一次干净对比:
#   ① 删除实例表 / 顶级配方 / 24 维边际价值表 —— 三者均由**已知最优解**倒推，
#      属于把答案发给考生。此前 _W/_X/_Y 三批 100+ 次运行的对比结论全部作废。
#   ② 改为 domain_rules():6 条通用规则，出处 petro-knowledge/05-生产优化.md
#      及 Jansen 2008、Van Essen 2011 —— 是领域先验而非解题结果。
#   ③ 领域知识**归角色所有**，经各角色 evidence 字段逐字转呈给总工;
#      无角色即无知识，这才是消融该有的语义。
#   ④ 无 Agent 臂移出本队列，改用不含 LLM 的平凡基线 B2/B4/BG。
#   守护:_tests/test_team.py 的两条泄露防线测试。
#
# 🔴 _Y 批次(2026-09-03)在 _X 基础上再修五处真实缺陷:
#   A. 守门员误杀好人 —— 注水量解析式 R2=0.219、最大误差 40.2pp，
#      把收益最高的 4 个方案(实测注水 -2.35%~+5.36%，完全合规)判成 +38%~+44%
#      超标而否决。改为「预测只警告，实测才裁定」。
#   B. 线性边际系数表在误导 —— 方案与该表吻合度和实测收益相关 **-0.29**，
#      越听越亏。整表删除，改给方案库实例。
#   C. 信息瓶颈 —— 总工只收到 7 份专家摘要(原始数据压缩 4.5 倍)，
#      从未直接见过实例表与时间/水量/油价。这使多角色臂的总工比无角色臂
#      **丢失**了直接信息通道。改为三臂总工看同一份原始事实。
#   D. 实例表抹掉井间结构 —— 只给时段平均，把"三口井猛砍 + F-4H 全程不动"
#      平均成 +0.03 的假象。改为逐格显示 theta[段][井]。
#   E. 删除基于已证伪解析式的过期论断("决定超预算的是形状不是幅度")。
#
# 🔴 _X 批次(2026-09-03)的四项数据/提示修正:
#   4. 给四个数据类角色补 (时段 x 井) 24 维边际价值表 —— 此前全部数据都不分时间，
#      专家无从得知"2008 年的一方水比 2017 年值 113 M$"。
#   5. 换算成真实单位:起止年/天数/当期 Brent 油价、基准注水量(万方)、
#      每方水净收益(USD/方)。抽象的"一个标准差"专家无法转成作业量。
#   6. 修正一处双重扣减:该表是**净值**(econ 已扣注水与采出水成本)，
#      此前误标为毛值并写了"低于成本、增注不赚钱"，导致候选全部反向加水。
#   7. 硬约束前置写进总工提示词，并给出实测的"形状比幅度更决定预算"对照表 ——
#      此前 55% 候选因超预算被否决，裸 LLM 因反复撞墙而整轮归零。
#
# 已知且**不做等化**的臂间差异(作为声明的限制写进结果，不假装不存在):
#   · LLM 调用预算:实测 full7≈48 次/运行、one1≈9、bare0≈6。三臂候选数(6)与
#     模拟预算(每轮 1)相同，额外调用不换取更多模拟机会，但确实换取更多推理。
#     每次运行的实际调用数已记入 loop_*.json 的 llm_calls 字段。
#   · 质疑轮只在 full7 触发(单 agent 无法与自己辩论)。这是"有团队"这一处理的
#     组成部分，属复合处理，论文中不得表述为"仅角色数不同"。
cd "$(dirname "$0")"
PY=/mnt/data/yongan-admin-2/envs/volve-chronos2/bin/python
L=../_pipelines/fc_team
REPS=${REPS:-10}
ALL="connectivity_analyst economics_analyst geomechanics_expert reservoir_engineer production_surveillance seismic_4d_analyst constraint_auditor"
# 单 Agent 臂保留 economics_analyst
SIX="connectivity_analyst economics_analyst geomechanics_expert production_surveillance seismic_4d_analyst constraint_auditor"

JOBS=()
# 🔴 _Z 批次:无 Agent 臂已移出本队列，改由 _code/fc_baselines.py 的
#    B2/B4/BG 三条**不含 LLM** 的平凡基线承担(此前的 bare0 是
#    "一个什么都不知道的 LLM 在提方案"，既非 Agent 也非正经基线)。
for k in $(seq 1 "$REPS"); do
  JOBS+=("full7|<none>|$k" "one1|$SIX|$k")
done
# 交错随机化:固定种子打乱，可复现
mapfile -t JOBS < <(printf '%s\n' "${JOBS[@]}" | shuf --random-source=<(yes 20260903))
echo "队列 ${#JOBS[@]}  重复 $REPS/臂  交错随机化  开始 $(date '+%F %T')"

run_one() {
  IFS='|' read -r grp drops k <<< "$1"
  tag="_F2${grp}_$k"
  [ -f "$L/loop$tag.json" ] && { echo "  跳过 $tag"; return; }
  if [ "$drops" = "<none>" ]; then D=(); else D=(--drop $drops); fi
  "$PY" -u fc_team_loop.py --model sonnet \
    --max-rounds 3 --n-cand 6 --n-sim 1 --threads 6 --device cpu \
    --c-inj 2.0 --c-prod 1.0 --w-max-dev 0.25 --tag "$tag" "${D[@]}" \
    > "$L/run$tag.log" 2>&1
  echo "  完成 $tag rc=$? $(date '+%T')"
}
export -f run_one; export PY L
printf '%s\n' "${JOBS[@]}" | xargs -P 3 -I{} bash -c 'run_one "$@"' _ {}
echo "队列结束 $(date '+%F %T')"
